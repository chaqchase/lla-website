#!/usr/bin/env node
// Turns raw Rex window captures into the figures the site serves.
//
//   node scripts/process-shots.mjs <raw-dir> [--pad <px>]
//
// Each capture is the full window. This trims the empty terminal rows below the output,
// then re-attaches the window's own bottom edge so the rounded corners stay intact, and
// writes public/shots/<name>.png plus the dimensions in lib/shots.ts. Shots missing from
// <raw-dir> keep their current file and dimensions, so a partial capture is safe to process.
import fs from 'node:fs'
import { createRequire } from 'node:module'
import path from 'node:path'

const require = createRequire(path.resolve('node_modules/next/package.json'))
const sharp = require('sharp')

const rawDir = process.argv[2]
const padIndex = process.argv.indexOf('--pad')
const PAD = padIndex > 0 ? Number(process.argv[padIndex + 1]) : 44
const BOTTOM_EDGE = 40 // rows kept from the real bottom of the window, corners included
const TITLE_BAR = 70
const CORNER = 26 // the window's corner radius in pixels, used for region captures
const outDir = 'public/shots'

fs.mkdirSync(outDir, { recursive: true })

const known = fs.existsSync('lib/shots.ts') ? fs.readFileSync('lib/shots.ts', 'utf8') : ''
const dimensions = Object.fromEntries(
  [...known.matchAll(/'([\w-]+)': \{ w: (\d+), h: (\d+) \}/g)].map(([, name, w, h]) => [name, { w: Number(w), h: Number(h) }])
)

for (const file of fs.readdirSync(rawDir).filter((name) => name.endsWith('.png')).sort()) {
  const name = path.basename(file, '.png')
  const input = sharp(path.join(rawDir, file)).ensureAlpha()
  const { data, info } = await input.raw().toBuffer({ resolveWithObject: true })
  const { width, height, channels } = info

  // Terminal background, sampled from just below the title bar.
  const at = (x, y) => (y * width + x) * channels
  const base = at(Math.floor(width / 2), TITLE_BAR + 6)
  const bg = [data[base], data[base + 1], data[base + 2]]

  let lastContentRow = TITLE_BAR
  for (let y = height - BOTTOM_EDGE - 1; y > TITLE_BAR; y--) {
    let found = false
    for (let x = 24; x < width - 24; x += 1) {
      const i = at(x, y)
      if (Math.abs(data[i] - bg[0]) + Math.abs(data[i + 1] - bg[1]) + Math.abs(data[i + 2] - bg[2]) > 24) {
        found = true
        break
      }
    }
    if (found) {
      lastContentRow = y
      break
    }
  }

  const keepTop = Math.min(lastContentRow + PAD, height - BOTTOM_EDGE)
  const finalHeight = keepTop + BOTTOM_EDGE
  const raw = { raw: { width, height, channels } }

  const top = await sharp(data, raw).extract({ left: 0, top: 0, width, height: keepTop }).png().toBuffer()
  const bottom = await sharp(data, raw)
    .extract({ left: 0, top: height - BOTTOM_EDGE, width, height: BOTTOM_EDGE })
    .png()
    .toBuffer()

  const window = await sharp({ create: { width, height: finalHeight, channels: 4, background: { r: 0, g: 0, b: 0, alpha: 0 } } })
    .composite([
      { input: top, top: 0, left: 0 },
      { input: bottom, top: keepTop, left: 0 }
    ])
    .png()
    .toBuffer()

  // A window capture has transparent corners. A region capture shows the desktop there, so cut it away.
  const opaqueCorner = data[at(0, 0) + 3] > 0
  const mask = Buffer.from(`<svg width="${width}" height="${finalHeight}"><rect width="${width}" height="${finalHeight}" rx="${CORNER}" ry="${CORNER}"/></svg>`)
  await sharp(window)
    .composite(opaqueCorner ? [{ input: mask, blend: 'dest-in' }] : [])
    .png({ compressionLevel: 9, palette: false })
    .toFile(path.join(outDir, `${name}.png`))

  dimensions[name] = { w: width, h: finalHeight }
  console.log(name.padEnd(28), `${width}x${finalHeight}`)
}

const body = Object.entries(dimensions)
  .map(([name, { w, h }]) => `  '${name}': { w: ${w}, h: ${h} }`)
  .join(',\n')

fs.writeFileSync(
  'lib/shots.ts',
  `// Generated by scripts/process-shots.mjs. Do not edit by hand.\nexport const shots = {\n${body}\n} as const\n\nexport type ShotName = keyof typeof shots\n`
)
